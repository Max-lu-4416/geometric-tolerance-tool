namespace Tolerance.Core;

public sealed record GradeAdvice(string Title, string Application, string Examples, string Note);

public static class GradeGuidance
{
    public static GradeAdvice For(ToleranceType type, string grade)
    {
        if (grade is "H" or "K" or "L")
        {
            string level = grade switch { "H" => "较严格", "K" => "中等", _ => "较宽松" };
            string application = $"{grade} 级用于未单独标注的几何公差，控制要求{level}；应按功能、加工与检测能力选用";
            string examples = GeneralToleranceCatalog.UnsupportedReason(type.Id);
            if (examples.Length == 0) examples = type.Id switch
            {
                "roundness" => "圆度：需输入直径尺寸公差，结果受径向圆跳动限值约束",
                "parallelism" => "平行度：需输入尺寸公差，并与相应直线度或平面度限值比较",
                "perpendicularity" => "垂直度：较长边作为基准，按较短边长度选值",
                "symmetry" => "对称度：至少一个要素为中心平面，或两要素轴线相互垂直；较长要素作为基准",
                "circular-runout" => "圆跳动：优先使用设计或工艺给定的支承面作为基准",
                "flatness" => "平面度：按表面的较长一侧或圆表面的直径选值",
                _ => "直线度：按相应被测线的长度选值"
            };
            return new($"{grade} 级 · 未注公差", application, examples, $"采用该等级时，技术要求可标注 GB/T 1184-{grade}；有单独公差要求的要素按单独标注执行");
        }
        if (!int.TryParse(grade, out int g)) return new("等级说明", "请选择有效等级", "", "");
        string app, example;
        if (type.TableId == "2-3-22")
        {
            (app, example) = g switch
            {
                1 or 2 => ("精密量具、测量仪器及精度要求极高的机械零件", "精密平尺、工具显微镜导轨面、喷油嘴针阀体端面"),
                3 => ("较高精度的量具工作面及测量仪器导向面", "0、1 级宽平尺工作面、量仪圆弧导轨和测杆"),
                4 => ("量具、测量仪器和高精度机床导轨", "0 级平板、量仪 V 形导轨、精密平面磨床导轨"),
                5 => ("精密机床工作台和导轨等工作表面", "1 级平板、平面磨床纵导轨与工作台、龙门刨床导轨"),
                6 => ("普通机床中有精度要求的导轨、工作台及结合面", "普通车床床身导轨、镗铣工作台、柴油机机体结合面"),
                7 => ("一般机床箱体、支承面及液压装置零件", "机床床头箱体、镗床工作台、液压泵盖、压力机滑块"),
                8 => ("一般箱体及机械结合面", "机床主轴箱体、车床溜板箱、气缸结合面、减速器壳体结合面"),
                9 => ("一般结合面和辅助机构支承面", "缸盖结合面、阀片、柴油机气缸体、手动机械支承面"),
                10 => ("要求较低的机体底面、壳体及连接面", "自动车床床身底面、变速箱壳体、法兰和液压管件连接面"),
                _ => ("易变形薄片、支架等精度要求不高的结合面", "离合器摩擦片、薄壳零件、支架及机床法兰等")
            };
        }
        else if (type.TableId == "2-3-23")
        {
            (app, example) = g switch
            {
                0 or 1 => ("高精度旋转零件及精密测量部件", "高精度量仪与机床主轴、滚动轴承滚珠和滚柱"),
                2 => ("精密主轴、精密阀套和喷油装置配合表面", "精密机床主轴轴颈、高压油泵柱塞及套、针阀圆柱表面"),
                3 => ("高精度磨床主轴及精密小型轴承部件", "工具显微镜套管、高精度外圆磨床主轴、喷油嘴针阀体"),
                4 => ("较精密机床主轴、箱体孔及高压液压零件", "精密主轴箱孔、高压阀门活塞、活塞销、高压油泵柱塞"),
                5 => ("一般主轴和较精密箱孔等配合表面", "一般机床主轴、柴油机活塞及销孔、空压机十字头销"),
                6 => ("普通机床、液压装置及通用传动配合表面", "一般机床主轴和箱孔、发动机凸轮轴、通用减速器轴颈"),
                7 => ("低速大功率发动机及一般液压传动零件", "柴油机曲轴、活塞、活塞销、千斤顶油缸活塞、水泵轴颈"),
                8 => ("低速发动机、减速器及普通机体零件", "压气机连杆、拖拉机气缸体、印刷传墨辊、柴油机气缸套"),
                9 => ("普通机械套筒和一般缸体表面", "空压机缸体、杠杆与拉杆套筒销子、活塞环套筒孔"),
                _ => ("较低精度的辊轴、绞车及滑动轴承轴颈", "印染机导布辊、绞车、吊车和起重机滑动轴承轴颈")
            };
        }
        else if (type.TableId == "2-3-24")
        {
            (app, example) = g switch
            {
                1 or 2 => ("同轴或旋转精度要求很高的精密零件", "精密测量仪器主轴和顶尖、柴油机喷油嘴针阀"),
                3 or 4 => ("高精度主轴及精密轴承零件", "机床主轴轴颈、砂轮轴、汽轮机主轴、高精度轴承内外圈"),
                5 => ("精度要求较高、应用较广的旋转零件", "机床轴颈、量仪测量杆、汽轮机主轴、柱塞油泵转子"),
                6 or 7 => ("常见动力与传动机构中的旋转零件", "内燃机曲轴、凸轮轴、水泵轴、齿轮轴、电机转子"),
                8 => ("一般精度的传动轴及旋转配合件", "拖拉机发动机分配轴轴颈"),
                9 => ("普通机械中一般精度的旋转配合表面", "齿轮轴配合面、水泵叶轮、离心泵泵体、精梳机滚子"),
                10 => ("精度要求较低的活塞、辊轴和气缸套", "摩托车活塞、印染机导布辊、活塞环槽底径、气缸套"),
                _ => ("无特殊同轴或旋转精度要求的一般零件", "普通零件的非关键旋转配合表面")
            };
        }
        else if (type.Id == "parallelism")
        {
            (app, example) = g switch
            {
                1 => ("高精度机床、测量仪器及量具的基准面和工作面", "高精度仪器主要基准面"),
                2 or 3 => ("精密机床、测量仪器、量具及模具的基准面", "精密机床重要箱体主轴孔对基准面的要求"),
                4 or 5 => ("普通机床、量具和模具中的重要基准与工作表面", "轴承座圈和端盖端面、重要轴承孔、减速器壳体孔"),
                >= 6 and <= 8 => ("一般机床零件、刀具、量具和模具", "一般轴承孔、床头箱孔、变速箱孔及传动轴"),
                9 or 10 => ("低精度零件和重型机械支承表面", "重型机械滚动轴承端盖"),
                _ => ("非工作面及精度要求较低的壳体表面", "卷扬机、输送机减速器壳体平面")
            };
        }
        else
        {
            (app, example) = g switch
            {
                1 => ("高精度机床、量仪及量具的基准面和工作面", "精密仪器主要基准面和工作面"),
                2 or 3 => ("精密机床导轨、主轴定位面和精密量具表面", "主轴轴肩端面、轴承座圈端面、齿轮测量仪心轴"),
                4 or 5 => ("普通机床导轨、重要支承面和精密机械零件", "机床重要支承面、主轴偏摆、液压传动轴瓦端面"),
                >= 6 and <= 8 => ("较低精度机床的主要基准、一般导轨和箱体孔", "回转工作台端面、主轴箱体孔、轴肩、活塞销孔"),
                9 or 10 => ("普通机械中精度要求较低的轴肩与端面", "花键轴轴肩、带式输送机法兰、减速器壳体平面"),
                _ => ("农业机械等精度要求较低的端面", "农业机械齿轮端面")
            };
        }
        return new($"{g} 级 · {type.Name}", app, example,
            "数字越小要求越严格。示例用于初选；应先满足功能要求，再兼顾加工经济性和检测能力");
    }
}
